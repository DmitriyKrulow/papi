#!/bin/bash
# ============================================================
# Обновление PAPI (Docker) — обёртка для старых ссылок и cron
# ============================================================
# Актуальный скрипт обновления лежит в корне проекта (update.sh):
# бэкап БД, обновление кода из git, пересборка образов,
# docker compose up -d и проверка здоровья db / backend / frontend (nginx).
#
# Файл нужен, чтобы не падали cron-задачи и ссылки вида
# ./scripts/update_docker.sh.
#
# Использование:
#   ./update.sh            (или ./scripts/update.sh, ./scripts/update_docker.sh)
#
# Для cron:
#   0 2 * * * /opt/papi/update.sh >> /var/log/papi-update.log 2>&1
# ============================================================

exec "$(cd "$(dirname "$0")/.." && pwd)/update.sh" "$@"
